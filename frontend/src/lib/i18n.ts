/** Translate a key with {param} interpolation. Falls back to English, then the key. */
export function translate(
  locale: Locale,
  key: string,
  params?: Record<string, string | number>,
): string {
  const raw = STRINGS[locale]?.[key] ?? STRINGS.en[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, p) =>
    params[p] !== undefined ? String(params[p]) : m,
  );
}

/** Convenience factory used inside components: const t = makeT(language). */
export function makeT(locale: Locale) {
  return (key: string, params?: Record<string, string | number>) =>
    translate(locale, key, params);
}

/** Server payloads carry these instead of prose. */
export interface Localised {
  code: string;
  params?: Record<string, string | number>;
}

export function renderLocalised(locale: Locale, l: Localised): string {
  return translate(locale, l.code, l.params);
}